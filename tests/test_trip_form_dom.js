const fs = require("node:fs");
const assert = require("node:assert/strict");
const {JSDOM} = require("jsdom");
const dom = new JSDOM('<div id="tripFormContent"></div>', {url: "https://example.test/", runScripts: "outside-only"});
const win = dom.window;
win.eval(fs.readFileSync("web/trip-form.js", "utf8"));
win.renderTripForm();
const fields = () => [...win.document.querySelectorAll(".trip-field")];
const field = name => fields().find(f => f.querySelector(":scope > label")?.textContent === name);
const budget = field("Budget");
assert(budget.querySelector('input[type="number"]'));
const select = budget.querySelector("select");
assert(select);
assert.equal(select.parentElement.style.display, "flex");
assert.deepEqual([...select.options].map(o => o.value), ["SGD","USD","SAR","EUR","GBP","CNY","JPY"]);
assert.equal(fields().filter(f => f.querySelector(":scope > label")?.textContent === "Budget currency").length, 0);
assert(!win.document.body.textContent.includes("Budgets are converted to SGD for planning"));
const start = field("Departure date").querySelector("input");
start.value = "2026-12-12";
start.dispatchEvent(new win.Event("input"));
const nights = win.document.querySelector('.trip-city input[type="number"]');
nights.value = "12";
nights.dispatchEvent(new win.Event("input"));
const end = field("Trip end date").querySelector("input");
assert.equal(end.value, "2026-12-24");
assert.equal(end.readOnly, true);
const add = [...win.document.querySelectorAll("button")].find(b => b.textContent === "+ Add another city");
add.click();
assert.equal(field("Trip end date").querySelector("input").value, "2026-12-26");
const section = title => [...win.document.querySelectorAll("details.trip-section")].find(d => d.querySelector("h3").textContent === title);
const titles = [...win.document.querySelectorAll(".trip-form-card")].map(c => c.querySelector("h3").textContent);
assert.deepEqual(titles, ["Destinations & route", "Travel details", "Flights", "Hotels", "Food & drinks", "Your days", "Additional requests"]);
assert(!section("Flights").open && section("Flights").querySelector(".badge").hidden);
assert.equal(section("Flights").querySelector(".trip-section-summary").textContent, "Economy, any stops, carry-on only");
assert(!win.document.body.textContent.includes("Hotel comfort") && !win.document.body.textContent.includes("Activity intensity"));
assert(!win.document.body.textContent.includes("Cafés & desserts"));
[...field("Cabin class").querySelectorAll("button")].find(b => b.textContent === "Business").click();
assert(!section("Flights").querySelector(".badge").hidden, "set badge after a change");
assert.equal(section("Flights").querySelector(".trip-section-summary").textContent, "Business, any stops, carry-on only");
[...field("Hotel stars").querySelectorAll("button")].find(b => b.textContent === "4★+").click();
[...field("Loyalty programs (optional)").querySelectorAll("button")].find(b => b.textContent === "Hilton Honors").click();
[...field("Pace").querySelectorAll("button")].find(b => b.textContent.startsWith("Packed")).click();
[...field("Coffee/tea stops per day").querySelectorAll("button")].find(b => b.textContent === "2").click();
const areas = fields().filter(f => f.querySelector(":scope > label")?.textContent.startsWith("Hotel area for destination"));
assert.equal(areas.length, 2);
areas[1].querySelector("input").value = "Gion";
areas[1].querySelector("input").dispatchEvent(new win.Event("input", {bubbles: true}));
assert(section("Hotels").querySelector(".trip-section-summary").textContent.endsWith("Hilton Honors, Gion"));
section("Hotels").open = true;
section("Hotels").dispatchEvent(new win.Event("toggle"));
add.click();   // re-render keeps the open section open
assert(section("Hotels").open && !section("Flights").open);
const lines = win.buildTripPrompt().split("\n");
assert(lines.includes("Flight preferences: business cabin"), lines);
assert(lines.some(l => l.startsWith("Hotel preferences: 4+ stars; loyalty programs Hilton Honors; area in ") && l.endsWith(": Gion")), lines);
assert(lines.includes("Your days: packed pace") && lines.includes("Food and drinks: 2 coffee or tea stops per day"), lines);
console.log("PASS: rendered budget controls, original date label, automatic and multi-city dates, collapsible preference sections");
win.close();
