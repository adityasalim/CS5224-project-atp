const fs = require('node:fs'), assert = require('node:assert/strict');
const {JSDOM} = require('jsdom');
const win = new JSDOM('<main></main>', {url:'https://example.test',runScripts:'outside-only'}).window;
win.el = (tag,cls,text) => {const e=win.document.createElement(tag);if(cls)e.className=cls;if(text!=null)e.textContent=text;return e;};
win.tripMoney=(x,c)=>c+' '+Number(x).toFixed(2);
const text=fs.readFileSync('web/index.html','utf8');
win.eval(text.split('/* ---------- agency package options ---------- */')[1].split('/* ---------- end agency package options ---------- */')[0]);
const p={packageId:'p',agencyId:'a',title:'<img src=x onerror=alert(1)>',agencyName:'Approved agency',contactEmail:'agency@example.test',reasons:['Culture fit'],tradeoffs:['Fixed schedule'],included:['Hotel'],excluded:['Flights'],comparison:{currency:'USD',packageTotal:'1000',knownExtras:'200',knownMinimumTotal:'1200',estimatedTotal:null,costComplete:false,missingCosts:['meals']}};
const card=win.renderPackageOptions({status:'recommended',packages:[p]},{currency:'USD'});
assert(card.textContent.includes('Full trip total unknown'));
assert(card.textContent.includes('not been confirmed within budget'));
assert(card.textContent.includes('USD 1000.00'));
assert(!card.querySelector('img'));
assert(card.querySelector('a').href.startsWith('mailto:'));
assert(win.packageEnquiryUrl({...p,contactEmail:'bad@example.test\r\nBcc:hacker@example.test'}, {})===null);
assert(win.renderPackageOptions({status:'no_suitable_packages',packages:[]},{}).textContent.includes('No agency package was recommended'));
assert(win.renderPackageOptions({status:'search_unavailable',packages:[]},{}).textContent.includes('temporarily unavailable'));
p.comparison={...p.comparison,costComplete:true,estimatedTotal:'1200',customVerified:true,customTotal:'1400'};
assert(win.renderPackageOptions({status:'recommended',packages:[p]},{currency:'USD'}).textContent.includes('Custom itinerary estimate: USD 1400.00'));
console.log('PASS package cards: complete/partial costs, enquiry draft, safe text and email, empty/error states');
win.close();
